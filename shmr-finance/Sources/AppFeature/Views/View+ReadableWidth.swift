import SwiftUI

extension View {

    // На iPad строка во всю ширину экрана читается плохо: от названия операции
    // до суммы глаз едет через полэкрана пустоты. Поэтому содержимое
    // ограничиваем по ширине и центрируем — так же ведут себя системные
    // приложения на большом экране. Фон при этом остаётся во всю ширину,
    // поэтому модификатор ставится до .background.
    //
    // На iPhone ограничение не срабатывает: экран и так уже.
    func readableWidth(_ maxWidth: CGFloat = 800) -> some View {
        frame(maxWidth: maxWidth)
            .frame(maxWidth: .infinity)
    }
}
